import React, { useState, useEffect } from "react";
import { createPortal } from "react-dom";
import { motion, AnimatePresence } from "framer-motion";
import {
  Sparkles,
  Loader2,
  ArrowRight,
  ArrowLeft,
  Clock,
  X,
  Target,
  Video,
  Palette,
  Smartphone,
  Layers,
  FileSpreadsheet,
} from "lucide-react";
import api from "@/lib/axios";
import { showSuccessToast, showErrorToast } from "@/components/utility/toast";

interface ProjectItem {
  project_id: string;
  name?: string;
  title?: string;
}

interface OrderDetailsProps {
  gigTitle: string;
  gigDescription?: string;
  category?: string;
  tierName?: string;
  projectBrief: string;
  setProjectBrief: (val: string) => void;
  initiatorRole: "Client" | "Freelancer";
  setInitiatorRole: (val: "Client" | "Freelancer") => void;
  isExistingProject: boolean;
  setIsExistingProject: (val: boolean) => void;
  existingProjectId: string | null;
  setExistingProjectId: (val: string | null) => void;
  projects: ProjectItem[];
  loadingProjects: boolean;
  projectsFetched: boolean;
  onNext: () => void;
  onBack: () => void;
}

const COOLDOWN_KEY = "ensemble_order_brief_ai_cooldown";

export const OrderDetails: React.FC<OrderDetailsProps> = ({
  gigTitle,
  gigDescription,
  category,
  tierName,
  projectBrief,
  setProjectBrief,
  initiatorRole,
  setInitiatorRole,
  isExistingProject,
  setIsExistingProject,
  existingProjectId,
  setExistingProjectId,
  projects,
  loadingProjects,
  projectsFetched,
  onNext,
  onBack,
}) => {
  // Joed AI Modal State
  const [isAiModalOpen, setIsAiModalOpen] = useState(false);
  const [aiPrompt, setAiPrompt] = useState("");
  const [isGeneratingAi, setIsGeneratingAi] = useState(false);
  const [aiError, setAiError] = useState<string | null>(null);
  const [aiCooldownLeft, setAiCooldownLeft] = useState<number>(0);

  // Initialize and run Cooldown Timer
  useEffect(() => {
    const raw = localStorage.getItem(COOLDOWN_KEY);
    if (!raw) return;
    const expiresAt = parseInt(raw, 10);
    const now = Date.now();
    if (expiresAt > now) {
      setAiCooldownLeft(Math.ceil((expiresAt - now) / 1000));
    } else {
      localStorage.removeItem(COOLDOWN_KEY);
    }
  }, []);

  useEffect(() => {
    if (aiCooldownLeft <= 0) return;
    const timer = setInterval(() => {
      setAiCooldownLeft((prev) => {
        if (prev <= 1) {
          localStorage.removeItem(COOLDOWN_KEY);
          return 0;
        }
        return prev - 1;
      });
    }, 1000);
    return () => clearInterval(timer);
  }, [aiCooldownLeft]);

  const aiPromptWordCount = aiPrompt.trim().split(/\s+/).filter(Boolean).length;
  const isGenerateDisabled =
    isGeneratingAi || aiCooldownLeft > 0 || aiPromptWordCount < 3;

  const handleGenerateWithAi = async () => {
    if (isGenerateDisabled) return;
    setIsGeneratingAi(true);
    setAiError(null);

    try {
      const res = await api.post("/api/chat/generate-order-brief", {
        prompt: aiPrompt,
        gigTitle,
        gigDescription,
        category,
        tierName,
      });

      if (res.data?.success && res.data?.data?.projectBrief) {
        setProjectBrief(res.data.data.projectBrief);
        // Set 3-minute cooldown
        const expiry = Date.now() + 180 * 1000;
        localStorage.setItem(COOLDOWN_KEY, String(expiry));
        setAiCooldownLeft(180);
        setIsAiModalOpen(false);
        showSuccessToast("Project brief generated by Joed AI!");
      } else {
        setAiError(res.data?.message || "Failed to generate project brief.");
      }
    } catch (err: any) {
      const msg =
        err?.response?.data?.message ||
        err?.message ||
        "Joed AI could not generate the project brief right now. Please try again.";
      setAiError(msg);
      showErrorToast(msg);
    } finally {
      setIsGeneratingAi(false);
    }
  };

  const handleApplyTemplate = () => {
    const template = `- Project Topic & Goal: 
- Raw Footage / Assets: 
- Desired Style & Music Vibe: 
- Platform & Target Duration: `;
    setAiPrompt((prev) => (prev.trim() ? `${prev}\n\n${template}` : template));
    if (aiError) setAiError(null);
  };

  const handleAppendDetail = (prefix: string) => {
    setAiPrompt((prev) => {
      const trimmed = prev.trim();
      if (!trimmed) return `${prefix}: `;
      return `${trimmed}\n${prefix}: `;
    });
    if (aiError) setAiError(null);
  };

  return (
    <div className="space-y-8">
      {/* 1. Project Brief Card */}
      <div className="rounded-2xl border border-gray-200 dark:border-white/10 bg-white dark:bg-dark-surface p-6 sm:p-7 shadow-sm space-y-4">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
          <div>
            <h2 className="text-base sm:text-lg font-bold text-gray-900 dark:text-white flex items-center gap-2">
              <span>Your Project Brief</span>
              <span className="text-red-500">*</span>
            </h2>
            <p className="text-xs text-gray-500 dark:text-zinc-400">
              Describe your project vision, target platform, raw footage status, and any specific styling references.
            </p>
          </div>

          {/* Joed AI Trigger Button */}
          <button
            type="button"
            onClick={() => setIsAiModalOpen(true)}
            className="flex items-center gap-2 px-3.5 py-1.5 rounded-xl bg-gradient-to-r from-blue-600 to-indigo-600 hover:from-blue-700 hover:to-indigo-700 text-white text-xs font-bold shadow-md shadow-blue-500/20 transition-all hover:scale-[1.02] active:scale-[0.98] shrink-0 self-start sm:self-auto cursor-pointer"
          >
            <Sparkles className="h-3.5 w-3.5" />
            <span>Generate with Joed AI!</span>
            {aiCooldownLeft > 0 && (
              <span className="text-[10px] bg-black/30 px-1.5 py-0.5 rounded font-mono">
                {Math.floor(aiCooldownLeft / 60)}:
                {String(aiCooldownLeft % 60).padStart(2, "0")}
              </span>
            )}
          </button>
        </div>

        {/* Brief Textarea */}
        <div className="space-y-1.5">
          <textarea
            rows={10}
            maxLength={1000}
            className="w-full rounded-xl border border-gray-200 dark:border-white/10 bg-gray-50/60 dark:bg-black/20 px-4 py-3 text-sm text-gray-900 dark:text-white outline-none focus:border-blue-500 focus:ring-2 focus:ring-blue-500/20 transition-all resize-none leading-relaxed placeholder:text-gray-400 dark:placeholder:text-zinc-500"
            placeholder="Tell the freelancer what you're creating. For example:
- Goal: Fast-paced YouTube tech review (approx. 8 minutes long)
- Tone: Sleek, high-energy, modern transitions with background lo-fi music
- Assets: We have 40GB of 4K Sony A7IV footage on Google Drive
- Deadlines: First rough cut needed within the agreed turnaround days..."
            value={projectBrief}
            onChange={(e) => setProjectBrief(e.target.value)}
          />
          <div className="flex justify-between items-center text-[11px] text-gray-400 dark:text-zinc-500">
            <span>Minimum detail helps the creator start faster.</span>
            <span
              className={`font-mono ${
                projectBrief.length >= 1000
                  ? "text-red-500 font-bold"
                  : projectBrief.length >= 800
                  ? "text-amber-500 font-bold"
                  : ""
              }`}
            >
              {projectBrief.length} / 1000 characters
            </span>
          </div>
        </div>
      </div>

      {/* 2. Platform & Workspace Questions Card */}
      <div className="rounded-2xl border border-gray-200 dark:border-white/10 bg-white dark:bg-dark-surface p-6 sm:p-7 shadow-sm space-y-5">
        <div>
          <h2 className="text-base sm:text-lg font-bold text-gray-900 dark:text-white mb-1">
            Collaboration &amp; Workspace Setup
          </h2>
          <p className="text-xs text-gray-500 dark:text-zinc-400">
            Determine who creates the cloud timeline and whether this order connects to an existing video project.
          </p>
        </div>

        {/* Initiator Role Selector */}
        <div className="space-y-2">
          <label className="text-xs font-bold text-gray-700 dark:text-zinc-300 uppercase tracking-wide block">
            Who will initiate the video project workspace? <span className="text-red-500">*</span>
          </label>
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
            <label
              className={`flex items-start gap-3 p-4 rounded-xl border-2 transition-all cursor-pointer ${
                initiatorRole === "Client"
                  ? "bg-blue-50/50 dark:bg-blue-950/20 border-blue-600 dark:border-blue-500"
                  : "bg-white dark:bg-dark-surface border-gray-200 dark:border-white/10 hover:border-gray-300 dark:hover:border-white/20"
              } ${
                projectsFetched && projects.length === 0 ? "opacity-60 cursor-not-allowed" : ""
              }`}
            >
              <input
                type="radio"
                name="initiatorRole"
                value="Client"
                disabled={projectsFetched && projects.length === 0}
                checked={initiatorRole === "Client"}
                onChange={() => {
                  setInitiatorRole("Client");
                  if (projects.length > 0) setIsExistingProject(true);
                }}
                className="mt-1 h-4 w-4 text-blue-600 focus:ring-blue-500 border-gray-300"
              />
              <div>
                <span className="text-sm font-bold text-gray-900 dark:text-white block">
                  Me (Client)
                </span>
                <span className="text-xs text-gray-500 dark:text-zinc-400 block mt-0.5">
                  I will host the project workspace and invite the freelancer to my files.
                </span>
              </div>
            </label>

            <label
              className={`flex items-start gap-3 p-4 rounded-xl border-2 transition-all cursor-pointer ${
                initiatorRole === "Freelancer"
                  ? "bg-blue-50/50 dark:bg-blue-950/20 border-blue-600 dark:border-blue-500"
                  : "bg-white dark:bg-dark-surface border-gray-200 dark:border-white/10 hover:border-gray-300 dark:hover:border-white/20"
              }`}
            >
              <input
                type="radio"
                name="initiatorRole"
                value="Freelancer"
                checked={initiatorRole === "Freelancer"}
                onChange={() => {
                  setInitiatorRole("Freelancer");
                  setIsExistingProject(false);
                  setExistingProjectId(null);
                }}
                className="mt-1 h-4 w-4 text-blue-600 focus:ring-blue-500 border-gray-300"
              />
              <div>
                <span className="text-sm font-bold text-gray-900 dark:text-white block">
                  The Freelancer
                </span>
                <span className="text-xs text-gray-500 dark:text-zinc-400 block mt-0.5">
                  The creator or studio will initialize the project and invite me once ready.
                </span>
              </div>
            </label>
          </div>
        </div>

        {/* Link to Existing Project */}
        {initiatorRole === "Client" && (
          <div className="pt-4 border-t border-gray-100 dark:border-white/5 space-y-3">
            <label className="flex items-start gap-3 cursor-pointer">
              <input
                type="checkbox"
                checked={isExistingProject}
                onChange={(e) => {
                  setIsExistingProject(e.target.checked);
                  if (!e.target.checked) setExistingProjectId(null);
                }}
                className="mt-1 h-4 w-4 rounded border-gray-300 text-blue-600 focus:ring-blue-500 cursor-pointer"
              />
              <div>
                <span className="text-sm font-bold text-gray-900 dark:text-white block">
                  Link to an Existing Ensemble Project
                </span>
                <span className="text-xs text-gray-500 dark:text-zinc-400 block mt-0.5">
                  Attach this order directly to an existing video editing timeline on your account.
                </span>
              </div>
            </label>

            {isExistingProject && (
              <div className="p-4 rounded-xl bg-gray-50 dark:bg-black/20 border border-gray-200 dark:border-white/10 space-y-2">
                <label className="text-[11px] font-bold text-gray-700 dark:text-zinc-300 uppercase tracking-wider block">
                  Select Project <span className="text-red-500">*</span>
                </label>
                {loadingProjects ? (
                  <div className="flex items-center gap-2 text-xs text-gray-500 py-1">
                    <Loader2 className="h-4 w-4 animate-spin text-blue-500" />
                    <span>Loading your projects...</span>
                  </div>
                ) : projects.length === 0 ? (
                  <div className="text-xs text-amber-600 dark:text-amber-400 italic">
                    No active projects found. You can let the freelancer initiate or create one first.
                  </div>
                ) : (
                  <select
                    value={existingProjectId || ""}
                    onChange={(e) => setExistingProjectId(e.target.value)}
                    className="w-full bg-white dark:bg-dark-surface border border-gray-200 dark:border-white/10 rounded-xl px-3 py-2.5 text-sm text-gray-900 dark:text-white focus:outline-none focus:ring-2 focus:ring-blue-500"
                  >
                    <option value="" disabled>
                      Choose an existing project...
                    </option>
                    {projects.map((p) => (
                      <option key={p.project_id} value={p.project_id}>
                        {p.name || p.title || p.project_id}
                      </option>
                    ))}
                  </select>
                )}
              </div>
            )}
          </div>
        )}
      </div>

      {/* Navigation Bar */}
      <div className="flex items-center justify-between gap-4 pt-2">
        <button
          type="button"
          onClick={onBack}
          className="flex items-center gap-1.5 px-5 py-2.5 rounded-xl border border-gray-200 dark:border-white/10 hover:bg-gray-100 dark:hover:bg-white/5 text-gray-700 dark:text-zinc-300 font-semibold text-xs transition cursor-pointer"
        >
          <ArrowLeft className="h-3.5 w-3.5" />
          <span>Back to Selection</span>
        </button>

        <button
          type="button"
          onClick={onNext}
          disabled={!projectBrief.trim()}
          className="flex items-center gap-2 px-6 py-2.5 rounded-xl bg-blue-600 hover:bg-blue-700 disabled:opacity-50 disabled:cursor-not-allowed text-white font-bold text-xs transition shadow-md shadow-blue-500/20 cursor-pointer"
        >
          <span>Next: Questions</span>
          <ArrowRight className="h-3.5 w-3.5" />
        </button>
      </div>

      {/* Generate with Joed AI Modal - Context Aware */}
      {typeof document !== "undefined" &&
        createPortal(
          <AnimatePresence>
            {isAiModalOpen && (
              <div className="fixed inset-0 z-[9999] flex items-center justify-center p-4">
                {/* Full-screen Backdrop */}
                <motion.div
                  initial={{ opacity: 0 }}
                  animate={{ opacity: 1 }}
                  exit={{ opacity: 0 }}
                  onClick={() => !isGeneratingAi && setIsAiModalOpen(false)}
                  className="fixed inset-0 bg-black/60 backdrop-blur-sm"
                />

                {/* Modal Container */}
                <motion.div
                  initial={{ opacity: 0, scale: 0.96, y: 12 }}
                  animate={{ opacity: 1, scale: 1, y: 0 }}
                  exit={{ opacity: 0, scale: 0.96, y: 12 }}
                  transition={{ duration: 0.2, ease: "easeOut" }}
                  className="relative w-full max-w-lg rounded-2xl bg-white dark:bg-zinc-900 border border-gray-200 dark:border-zinc-800 shadow-2xl overflow-hidden z-10 flex flex-col max-h-[92vh]"
                >
                  {/* Modal Header */}
                  <div className="px-6 py-4 border-b border-gray-100 dark:border-zinc-800 flex items-center justify-between">
                    <div className="flex items-center gap-3">
                      <img
                        src="/ensemble_lg.svg"
                        alt="Ensemble"
                        className="h-7 w-7 shrink-0 invert dark:invert-0 object-contain"
                      />
                      <div>
                        <h3 className="text-base font-bold text-gray-900 dark:text-white tracking-tight">
                          Generate Brief with Joed AI!
                        </h3>
                        <p className="text-xs text-gray-500 dark:text-zinc-400 mt-0.5">
                          Tuned specifically for this freelancer's service offering.
                        </p>
                      </div>
                    </div>
                    <button
                      type="button"
                      onClick={() => !isGeneratingAi && setIsAiModalOpen(false)}
                      className="p-1.5 rounded-lg text-gray-400 hover:text-gray-700 dark:text-zinc-500 dark:hover:text-zinc-300 hover:bg-gray-100 dark:hover:bg-zinc-800 transition cursor-pointer"
                      title="Close"
                    >
                      <X className="h-4 w-4" />
                    </button>
                  </div>

                  {/* Modal Body */}
                  <div className="p-6 space-y-4 overflow-y-auto thin-gallery-scrollbar">
                    {/* Service Context Snapshot Card */}
                    <div className="p-3.5 rounded-xl border border-blue-200 dark:border-blue-900/40 bg-blue-50/50 dark:bg-blue-950/20 space-y-1.5">
                      <div className="flex items-center gap-1.5 text-[10px] font-bold text-blue-600 dark:text-blue-400 uppercase tracking-wider">
                        <Layers className="h-3 w-3" />
                        <span>Analyzing Service Context</span>
                        {category && <span className="text-gray-400 dark:text-zinc-500">&bull; {category}</span>}
                        {tierName && <span className="text-gray-400 dark:text-zinc-500">&bull; {tierName}</span>}
                      </div>
                      <h4 className="text-xs sm:text-sm font-bold text-gray-900 dark:text-white line-clamp-2">
                        {gigTitle}
                      </h4>
                      {gigDescription && (
                        <p className="text-[11px] text-gray-600 dark:text-zinc-400 line-clamp-2 leading-relaxed">
                          {gigDescription.replace(/[*_#]/g, "")}
                        </p>
                      )}
                    </div>

                    {/* Contextual Guidance: What Joed AI needs from you */}
                    <div className="space-y-2">
                      <div className="flex items-center justify-between">
                        <span className="text-[11px] font-bold text-gray-700 dark:text-zinc-300 uppercase tracking-wider">
                          Tell Joed AI about your video
                        </span>
                        <button
                          type="button"
                          onClick={handleApplyTemplate}
                          className="inline-flex items-center gap-1 text-[11px] font-semibold text-blue-600 dark:text-blue-400 hover:underline cursor-pointer"
                        >
                          <FileSpreadsheet className="h-3 w-3" />
                          <span>Insert Template</span>
                        </button>
                      </div>

                      {/* Quick Detail Helper Chips */}
                      <div className="flex flex-wrap gap-1.5">
                        <button
                          type="button"
                          onClick={() => handleAppendDetail("Project Goal")}
                          className="inline-flex items-center gap-1.5 px-2.5 py-1 rounded-lg text-[11px] font-medium bg-gray-100 hover:bg-gray-200 dark:bg-zinc-800 dark:hover:bg-zinc-700 text-gray-700 dark:text-zinc-300 transition-colors cursor-pointer"
                        >
                          <Target className="h-3 w-3 text-blue-500" />
                          <span>+ Goal &amp; Topic</span>
                        </button>

                        <button
                          type="button"
                          onClick={() => handleAppendDetail("Raw Footage / Assets")}
                          className="inline-flex items-center gap-1.5 px-2.5 py-1 rounded-lg text-[11px] font-medium bg-gray-100 hover:bg-gray-200 dark:bg-zinc-800 dark:hover:bg-zinc-700 text-gray-700 dark:text-zinc-300 transition-colors cursor-pointer"
                        >
                          <Video className="h-3 w-3 text-amber-500" />
                          <span>+ Raw Footage &amp; Length</span>
                        </button>

                        <button
                          type="button"
                          onClick={() => handleAppendDetail("Desired Style & Vibe")}
                          className="inline-flex items-center gap-1.5 px-2.5 py-1 rounded-lg text-[11px] font-medium bg-gray-100 hover:bg-gray-200 dark:bg-zinc-800 dark:hover:bg-zinc-700 text-gray-700 dark:text-zinc-300 transition-colors cursor-pointer"
                        >
                          <Palette className="h-3 w-3 text-emerald-500" />
                          <span>+ Style &amp; Pacing</span>
                        </button>

                        <button
                          type="button"
                          onClick={() => handleAppendDetail("Platform & Duration")}
                          className="inline-flex items-center gap-1.5 px-2.5 py-1 rounded-lg text-[11px] font-medium bg-gray-100 hover:bg-gray-200 dark:bg-zinc-800 dark:hover:bg-zinc-700 text-gray-700 dark:text-zinc-300 transition-colors cursor-pointer"
                        >
                          <Smartphone className="h-3 w-3 text-purple-500" />
                          <span>+ Platform &amp; Format</span>
                        </button>
                      </div>

                      {/* Prompt Textarea */}
                      <div className="space-y-1 pt-1">
                        <textarea
                          rows={5}
                          maxLength={1000}
                          placeholder={`Give Joed AI your project specifics related to this service, e.g.:
- I have 30 minutes of raw 1080p clips from our team match.
- Need a 2-minute montage synced to high-bpm music with glitch effects, sound design, and clean player kill titles.`}
                          value={aiPrompt}
                          onChange={(e) => {
                            setAiPrompt(e.target.value);
                            if (aiError) setAiError(null);
                          }}
                          className={`w-full rounded-xl border bg-gray-50/50 dark:bg-zinc-800/40 p-3.5 text-xs text-gray-900 dark:text-white outline-none focus:bg-white dark:focus:bg-zinc-800 placeholder:text-gray-400 dark:placeholder:text-zinc-500 leading-relaxed resize-none font-medium transition-all ${
                            aiError
                              ? "border-red-400 dark:border-red-500/60 focus:border-red-500 focus:ring-4 focus:ring-red-500/10"
                              : "border-gray-200 dark:border-zinc-700/80 focus:border-blue-500 focus:ring-4 focus:ring-blue-500/10"
                          }`}
                        />
                        <div className="flex justify-between items-center text-[10px] text-gray-400">
                          <span
                            className={
                              aiPromptWordCount < 3 && aiPrompt.length > 0
                                ? "text-amber-500 font-semibold"
                                : ""
                            }
                          >
                            {aiPromptWordCount} words (min 3 required)
                          </span>
                          <span className="font-mono">{aiPrompt.length}/1000</span>
                        </div>
                      </div>

                      {aiError && (
                        <p className="text-[11px] font-medium text-red-500 dark:text-red-400 mt-1">
                          {aiError}
                        </p>
                      )}
                    </div>

                    {/* Cooldown notice */}
                    <div className="flex items-center gap-2 px-3 py-2 rounded-xl bg-gray-50 dark:bg-zinc-800/60 border border-gray-200 dark:border-zinc-700/70 text-xs text-gray-600 dark:text-zinc-300">
                      <Clock className="h-4 w-4 shrink-0 text-gray-400 dark:text-zinc-400" />
                      <span className="font-medium">
                        {aiCooldownLeft > 0
                          ? `Cooldown active: ${Math.floor(aiCooldownLeft / 60)}:${String(
                              aiCooldownLeft % 60
                            ).padStart(2, "0")} remaining.`
                          : "3-minute cooldown applies after generation."}
                      </span>
                    </div>
                  </div>

                  {/* Modal Footer */}
                  <div className="px-6 py-3.5 border-t border-gray-100 dark:border-zinc-800 bg-gray-50/40 dark:bg-zinc-900/40 flex items-center justify-between gap-3">
                    <button
                      type="button"
                      disabled={isGeneratingAi}
                      onClick={() => setIsAiModalOpen(false)}
                      className="px-4 py-2 rounded-xl border border-gray-200 dark:border-zinc-700 text-gray-700 dark:text-zinc-300 text-xs font-bold hover:bg-gray-100 dark:hover:bg-zinc-800 transition cursor-pointer disabled:opacity-50 disabled:cursor-not-allowed"
                    >
                      Cancel
                    </button>

                    <button
                      type="button"
                      disabled={isGenerateDisabled}
                      onClick={handleGenerateWithAi}
                      className={`px-5 py-2.5 rounded-xl text-xs font-bold transition flex items-center gap-2 ${
                        !isGenerateDisabled
                          ? "bg-blue-600 hover:bg-blue-500 text-white shadow-md shadow-blue-500/25 active:scale-[0.98] cursor-pointer"
                          : "bg-gray-100 dark:bg-zinc-800/80 text-gray-400 dark:text-zinc-500 border border-gray-200 dark:border-zinc-700/60 cursor-not-allowed opacity-70"
                      }`}
                      title={
                        isGeneratingAi
                          ? "Joed AI is generating your project brief..."
                          : aiCooldownLeft > 0
                          ? `Cooldown active (${aiCooldownLeft}s)`
                          : aiPromptWordCount < 3
                          ? "Please write at least 3 words to generate"
                          : "Generate Project Brief with Joed AI"
                      }
                    >
                      {isGeneratingAi ? (
                        <>
                          <Loader2 className="h-3.5 w-3.5 animate-spin text-blue-500" />
                          <span>Generating with Joed AI...</span>
                        </>
                      ) : (
                        <>
                          <Sparkles
                            className={`h-3.5 w-3.5 ${
                              !isGenerateDisabled ? "text-white" : "text-gray-400 dark:text-zinc-500"
                            }`}
                          />
                          <span>Generate Now</span>
                        </>
                      )}
                    </button>
                  </div>
                </motion.div>
              </div>
            )}
          </AnimatePresence>,
          document.body
        )}
    </div>
  );
};

export default OrderDetails;
